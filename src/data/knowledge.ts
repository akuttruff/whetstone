import type { Difficulty, PromptProblem } from '../types.ts'

/** Compact constructor so the question bank below stays readable. */
function q(
  id: string,
  topic: string,
  pattern: string,
  difficulty: Difficulty,
  title: string,
  question: string | string[],
  keyPoints: string[],
  followUps: string[] = [],
): PromptProblem {
  return {
    id, track: 'knowledge', source: 'builtin', title, topic, pattern, difficulty,
    question: Array.isArray(question) ? question : [question],
    keyPoints,
    followUps,
  }
}

